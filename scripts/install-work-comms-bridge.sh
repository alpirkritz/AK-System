#!/usr/bin/env bash
# Install (or reinstall) the local work-comms bridge as a launchd agent.
# Pulls Outlook mail + Slack (and Teams, once enabled) into the local SQLite every 15 min
# while this Mac is awake, using the signed-in browser sessions — same approach as the
# Outlook calendar bridge.
#
#   bash scripts/install-work-comms-bridge.sh            # install + load
#   bash scripts/install-work-comms-bridge.sh --uninstall # unload + remove
#
# Prerequisites (one-time, interactive):
#   pnpm exec tsx scripts/owa-login.ts     # Outlook mail (shares the calendar bridge profile)
#   pnpm exec tsx scripts/slack-login.ts   # Slack web session
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"

LABEL="com.ak.work-comms-bridge"
TEMPLATE="$ROOT_DIR/deploy/launchd/${LABEL}.plist"
AGENTS_DIR="$HOME/Library/LaunchAgents"
TARGET="$AGENTS_DIR/${LABEL}.plist"
LOCAL_DIR="$HOME/.ak-system"
LOCAL_RUNNER="$LOCAL_DIR/work-comms-run.sh"
LOCAL_LOG="$LOCAL_DIR/work-comms-bridge.log"
REPO_RUNNER="$ROOT_DIR/scripts/work-comms-bridge-run.sh"

if [ "$(uname)" != "Darwin" ]; then
  echo "✗  The work-comms bridge only runs on macOS."
  exit 1
fi

uninstall() {
  launchctl bootout "gui/$(id -u)/${LABEL}" 2>/dev/null || launchctl unload "$TARGET" 2>/dev/null || true
  rm -f "$TARGET" "$LOCAL_RUNNER"
  echo "✓  Uninstalled ${LABEL}."
}

if [ "${1:-}" = "--uninstall" ]; then
  uninstall
  exit 0
fi

[ -f "$TEMPLATE" ] || { echo "✗  Missing template $TEMPLATE"; exit 1; }
[ -f "$REPO_RUNNER" ] || { echo "✗  Missing runner $REPO_RUNNER"; exit 1; }

mkdir -p "$AGENTS_DIR" "$LOCAL_DIR"

# A thin local runner launchd can execute (the repo lives in Google Drive, which launchd
# cannot run scripts from directly). It just delegates to the repo runner.
cat > "$LOCAL_RUNNER" <<EOF
#!/usr/bin/env bash
# Generated by scripts/install-work-comms-bridge.sh — do not edit by hand.
set -euo pipefail
export WORK_COMMS_LOG="${LOCAL_LOG}"
exec bash "${REPO_RUNNER}"
EOF
chmod +x "$LOCAL_RUNNER"

# Substitute the plist template and install it.
sed -e "s#__RUN_SCRIPT__#${LOCAL_RUNNER}#g" \
    -e "s#__WORKDIR__#${ROOT_DIR}#g" \
    -e "s#__LOG__#${LOCAL_LOG}#g" \
    "$TEMPLATE" > "$TARGET"

launchctl bootout "gui/$(id -u)/${LABEL}" 2>/dev/null || launchctl unload "$TARGET" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$TARGET" 2>/dev/null || launchctl load "$TARGET"

echo "✓  Installed ${LABEL} — runs every 15 min."
echo "   Log: ${LOCAL_LOG}"
echo "   First run happens now (RunAtLoad). Tail it with:"
echo "     tail -f \"${LOCAL_LOG}\""
echo
echo "   If a source reports an expired session, re-authenticate:"
echo "     pnpm exec tsx scripts/owa-login.ts     # Outlook mail"
echo "     pnpm exec tsx scripts/slack-login.ts   # Slack"
